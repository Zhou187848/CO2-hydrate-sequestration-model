function c=modern_configuration(user)
% 算例共用的水合物热力学参数。
if nargin<1, user=struct(); end
root=fileparts(mfilename('fullpath'));
cal=jsondecode(fileread(fullfile(root,'caloric_reference.json')));
c=struct('name','baseline_2d','closure','li2024_moridis2025_v1',...
    'results_folder','results_modern_caloric','wc',cal.wc,'rho_h',cal.rho_h,...
    'cp_h',cal.cp_h,'cp_h_slope',cal.cp_h_slope,'hydrate_u0',cal.hydrate_u0,...
    'radius',2000,'nr',62,'z_refine',1,'dt_initial',.01,'dt_min',1e-6,...
    'duration',864000,'dt_max',3600,'verbose',true);
f=fieldnames(user); for j=1:numel(f), c.(f{j})=user.(f{j}); end
end
