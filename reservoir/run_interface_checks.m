function run_interface_checks()
% 网格、时间步、边界条件和停注对照。
base=struct('well_control','common_bhp','inject_temperature',5.50,...
    'sand_k',140*9.869233e-16,'results_folder','results_interface_final','snapshot_days',[.5,1,2,3,5,7,10]);
cases={struct('name','nearwell_x2','nearwell_refine',2),...
    struct('name','nearwell_x4','nearwell_refine',4),...
    struct('name','permeability_n2','permeability_exponent',2),...
    struct('name','permeability_n6','permeability_exponent',6),...
    struct('name','grid_fine','nr',93,'z_refine',1.5),...
    struct('name','time_half','dt_max',1800)};
for j=1:numel(cases)
    c=base; f=fieldnames(cases{j});
    for k=1:numel(f),c.(f{k})=cases{j}.(f{k});end
    o=axisymmetric_co2(modern_configuration(c));
    assert(abs(o.summary.CO2_defect_kg)/o.summary.injected_kg<1e-6);
end
run_modern_suite('checks',1,1,base);
end
